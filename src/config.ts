import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

try {
  process.loadEnvFile(resolve(ROOT, ".env"));
} catch {
  /* .env is optional. */
}

export interface Config {
  root: string;
  dataDir: string;
  dbPath: string;
  host: string;
  port: number;
  baseUrl: string;
  timezone: string;
  user: string;
  password: string;
  readToken: string;
  actor: string;
  nowOverride: string | undefined;
  caddyHost: string;
  caddyNetwork: string;
  coverageThreshold: number;
  adherenceThreshold: number;
  goalHours: number;
  demo: boolean;
}

function numberFrom(value: string | undefined, fallback: number): number {
  const parsed = Number(value);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
}

export function loadConfig(env: NodeJS.ProcessEnv = process.env): Config {
  const text = (key: string, fallback: string) => env[key] ?? fallback;
  const dataDir = resolve(text("DAY_DATA_DIR", resolve(ROOT, "data")));
  const dbPath = resolve(text("DAY_DB_PATH", resolve(dataDir, "day.sqlite")));
  const port = numberFrom(env.DAY_PORT, 3037);
  const host = text("DAY_HOST", "127.0.0.1");
  return {
    root: ROOT,
    dataDir,
    dbPath,
    host,
    port,
    baseUrl: text("DAY_BASE_URL", `http://${host}:${port}`),
    timezone: text("DAY_TZ", "Europe/Warsaw"),
    user: text("DAY_USER", "day"),
    password: text("DAY_PASSWORD", "day"),
    readToken: text("DAY_READ_TOKEN", "example-read-token"),
    actor: text("DAY_ACTOR", "cli"),
    nowOverride: env.DAY_NOW,
    caddyHost: text("DAY_CADDY_HOST", "day.home.br11k.dev"),
    caddyNetwork: text("DAY_CADDY_NETWORK", "caddy"),
    coverageThreshold: numberFrom(env.DAY_COVERAGE_THRESHOLD, 0.9),
    adherenceThreshold: numberFrom(env.DAY_ADHERENCE_THRESHOLD, 0.8),
    goalHours: numberFrom(env.DAY_GOAL_HOURS, 3),
    demo: env.DAY_DEMO === "1",
  };
}

export function ensureDataDir(config: Config): void {
  mkdirSync(config.dataDir, { recursive: true });
}

export function ensureEnvFile(config: Config): { created: boolean; path: string } {
  const path = resolve(config.root, ".env");
  if (existsSync(path)) return { created: false, path };
  const contents = [
    "# Generated by `day setup`. Keep this file private.",
    `DAY_PORT=${config.port}`,
    `DAY_HOST=${config.host}`,
    `DAY_TZ=${config.timezone}`,
    `DAY_USER=${config.user}`,
    `DAY_PASSWORD=${randomBytes(12).toString("hex")}`,
    `DAY_READ_TOKEN=${randomBytes(24).toString("hex")}`,
    `DAY_CADDY_HOST=${config.caddyHost}`,
    `DAY_CADDY_NETWORK=${config.caddyNetwork}`,
    "DAY_COVERAGE_THRESHOLD=0.9",
    "DAY_ADHERENCE_THRESHOLD=0.8",
    "DAY_GOAL_HOURS=3",
    "",
  ].join("\n");
  writeFileSync(path, contents, { mode: 0o600 });
  return { created: true, path };
}

export function readEnvValue(key: string): string | undefined {
  try {
    const text = readFileSync(resolve(ROOT, ".env"), "utf8");
    const line = text.split("\n").find((row) => row.startsWith(`${key}=`));
    return line?.slice(key.length + 1);
  } catch {
    return undefined;
  }
}
